func TestEditTOMLStringsChangesOnlyTheDomainLines(t *testing.T) {
	orig := installerTOML("old.example", "127.0.0.1")
	out, err := editTOMLStrings([]byte(orig), domainTOMLEdits(newNames))
	if err != nil {
		t.Fatal(err)
	}
	a, b := strings.Split(orig, "\n"), strings.Split(string(out), "\n")
	if len(a) != len(b) {
		t.Fatalf("line count %d → %d:\n%s", len(a), len(b), out)
	}
	changed := map[string]string{}
	for i := range a {
		if a[i] != b[i] {
			changed[a[i]] = b[i]
		}
	}
	want := map[string]string{
		`root_domain = "old.example"`:               `root_domain = "new.example"`,
		`admin_hostname = "op.console.old.example"`: `admin_hostname = "op.console.new.example"`,
		`panel_hostname = "console.old.example"`:    `panel_hostname = "console.new.example"`,
	}
	if len(changed) != len(want) {
		t.Fatalf("changed lines %v, want %v", changed, want)
	}
	for k, v := range want {
		if changed[k] != v {
			t.Errorf("%q → %q, want %q", k, changed[k], v)
		}
	}
}

