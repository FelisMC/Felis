// caSignedCert is an operator's certificate from their own CA; it names
// localhost too, so only the issuer tells it apart from the installer's.
func caSignedCert(t *testing.T, hosts ...string) (certPEM, keyPEM []byte) {
	t.Helper()
	caKey, _ := rsa.GenerateKey(rand.Reader, 2048)
	ca := &x509.Certificate{SerialNumber: big.NewInt(1), Subject: pkix.Name{CommonName: "Corp CA"}, IsCA: true,
		BasicConstraintsValid: true, KeyUsage: x509.KeyUsageCertSign, NotBefore: time.Now().Add(-time.Hour), NotAfter: time.Now().Add(time.Hour)}
	caDER, err := x509.CreateCertificate(rand.Reader, ca, ca, &caKey.PublicKey, caKey)
	if err != nil {
		t.Fatal(err)
	}
	caCert, _ := x509.ParseCertificate(caDER)
	key, _ := rsa.GenerateKey(rand.Reader, 2048)
	leaf := &x509.Certificate{SerialNumber: big.NewInt(2), Subject: pkix.Name{CommonName: hosts[0]},
		DNSNames: append(hosts, "localhost"), IPAddresses: []net.IP{net.IPv4(127, 0, 0, 1)},
		NotBefore: time.Now().Add(-time.Hour), NotAfter: time.Now().Add(time.Hour)}
	der, err := x509.CreateCertificate(rand.Reader, leaf, caCert, &key.PublicKey, caKey)
	if err != nil {
		t.Fatal(err)
	}
	pk, _ := x509.MarshalPKCS8PrivateKey(key)
	return pem.EncodeToMemory(&pem.Block{Type: "CERTIFICATE", Bytes: der}), pem.EncodeToMemory(&pem.Block{Type: "PRIVATE KEY", Bytes: pk})
}

func TestFelisIssuedCert(t *testing.T) {
	mine, _, err := issuePanelCert(oldNames, nil, time.Now())
	if err != nil {
		t.Fatal(err)
	}
	c, _ := x509.ParseCertificate(mustCertDER(mine))
	if !felisIssuedCert(c) {
		t.Error("the installer's kind of certificate is not recognised as Felis-issued")
	}
	theirs, _ := caSignedCert(t, "console.old.example")
	c, _ = x509.ParseCertificate(mustCertDER(theirs))
	if felisIssuedCert(c) {
		t.Error("a CA-signed certificate is taken for Felis-issued")
	}

	// Self-signed but without one of the installer's localhost names: someone
	// else's.
	key, _ := rsa.GenerateKey(rand.Reader, 2048)
	for name, self := range map[string]*x509.Certificate{
		"no localhost": {DNSNames: []string{"console.old.example"}, IPAddresses: []net.IP{net.IPv4(127, 0, 0, 1)}},
		"no 127.0.0.1": {DNSNames: []string{"console.old.example", "localhost"}},
	} {
		self.SerialNumber, self.Subject = big.NewInt(3), pkix.Name{CommonName: "x"}
		self.NotBefore, self.NotAfter = time.Now().Add(-time.Hour), time.Now().Add(time.Hour)
		der, _ := x509.CreateCertificate(rand.Reader, self, self, &key.PublicKey, key)
		c, _ = x509.ParseCertificate(der)
		if felisIssuedCert(c) {
			t.Errorf("%s: a self-signed certificate is taken for Felis-issued", name)
		}
	}
}

func TestIssuePanelCertIsTheInstallersShape(t *testing.T) {
	now := time.Now()
	certPEM, keyPEM, err := issuePanelCert(newNames, []net.IP{net.ParseIP("10.211.55.6"), net.IPv4(127, 0, 0, 1)}, now)
	if err != nil {
		t.Fatal(err)
	}
	if _, err := tls.X509KeyPair(certPEM, keyPEM); err != nil {
		t.Fatalf("key does not match the certificate: %v", err)
	}
	if b, _ := pem.Decode(keyPEM); b == nil || b.Type != "PRIVATE KEY" {
		t.Fatalf("key is not PKCS#8 PEM like openssl writes")
	}
	c, _ := x509.ParseCertificate(mustCertDER(certPEM))
	if !certCovers(c, newNames.panel, newNames.admin, "localhost") || !felisIssuedCert(c) {
		t.Fatalf("names %v", c.DNSNames)
	}
	if len(c.IPAddresses) != 2 || !c.IPAddresses[1].Equal(net.ParseIP("10.211.55.6")) {
		t.Fatalf("addresses %v, want 127.0.0.1 and the node address once each", c.IPAddresses)
	}
	if c.Subject.CommonName != newNames.admin || c.NotAfter.Sub(now) < 824*24*time.Hour || c.NotAfter.Sub(now) > 826*24*time.Hour {
		t.Fatalf("CN %q, valid until %s", c.Subject.CommonName, c.NotAfter)
	}
	if len(c.ExtKeyUsage) != 1 || c.ExtKeyUsage[0] != x509.ExtKeyUsageServerAuth || c.IsCA {
		t.Fatalf("usage %v, CA %v", c.ExtKeyUsage, c.IsCA)
	}
}

func TestDomainSetMovesEverySurface(t *testing.T) {
	rig := newDomainRig(t)
	hostBefore := rig.read(t, "felis.host.toml")
	code, err := rig.h.set(context.Background(), "New.Example", true)
	if err != nil || code != 0 {
		t.Fatalf("set = %d, %v\n%s", code, err, rig.out)
	}

	// The configs: the three values moved, everything else — comments, the
	// database host of each copy, the Access audience — is as it was.
	host := rig.read(t, "felis.host.toml")
	if want := strings.NewReplacer("old.example", "new.example").Replace(hostBefore); host != want {
		t.Fatalf("host toml:\n%s", host)
	}
	pod := rig.read(t, "felis.pod.toml")
	if got, _ := tomlDomainNames([]byte(pod)); got != newNames || !strings.Contains(pod, "@10.211.55.6:5432") {
		t.Fatalf("pod toml:\n%s", pod)
	}
	if link, err := os.Readlink(rig.path("felis.toml")); err != nil || link != rig.path("felis.host.toml") {
		t.Fatalf("felis.toml is no longer the link to the host copy: %q %v", link, err)
	}
	if st, _ := os.Stat(rig.path("felis.host.toml")); st.Mode().Perm() != 0o600 {
		t.Fatalf("host toml mode %v", st.Mode().Perm())
	}

	// The certificate: reissued for the new names, the node address kept, the old
	// pair beside it.
	c, err := readCertFile(rig.path("panel-tls.crt"))
	if err != nil || !certCovers(c, newNames.panel, newNames.admin) || !felisIssuedCert(c) {
		t.Fatalf("certificate: %v %v", err, c.DNSNames)
	}
	if !c.IPAddresses[len(c.IPAddresses)-1].Equal(net.ParseIP("10.211.55.6")) {
		t.Fatalf("addresses %v", c.IPAddresses)
	}
	if _, err := tls.LoadX509KeyPair(rig.path("panel-tls.crt"), rig.path("panel-tls.key")); err != nil {
		t.Fatalf("new pair: %v", err)
	}
	if st, _ := os.Stat(rig.path("panel-tls.key")); st.Mode().Perm() != 0o600 {
		t.Fatalf("key mode %v", st.Mode().Perm())
	}
	backups, _ := filepath.Glob(rig.path("panel-tls.*.pre-domain-*"))
	if len(backups) != 2 {
		t.Fatalf("old pair kept as %v", backups)
	}
	for _, b := range backups {
		if st, _ := os.Stat(b); strings.Contains(b, ".key.") && st.Mode().Perm() != 0o600 {
			t.Fatalf("kept key %s has mode %v", b, st.Mode().Perm())
		}
		old, _ := os.ReadFile(b)
		if strings.Contains(b, ".crt.") {
			oc, _ := x509.ParseCertificate(mustCertDER(old))
			if oc == nil || !certCovers(oc, oldNames.panel) {
				t.Fatalf("kept certificate is not the old one")
			}
		}
	}

	// The Secrets carry the files.
	for _, ns := range []string{"felis", "minecraft"} {
		if got := rig.secret(t, ns, platform.ConfigSecretName)[platform.ConfigSecretKey]; string(got) != pod {
			t.Fatalf("%s/felis-config is not felis.pod.toml", ns)
		}
	}
	tlsData := rig.secret(t, "felis", platform.APITLSSecretName)
	if string(tlsData[corev1.TLSCertKey]) != rig.read(t, "panel-tls.crt") || string(tlsData[corev1.TLSPrivateKeyKey]) != rig.read(t, "panel-tls.key") {
		t.Fatal("felis-api-tls does not hold the new pair")
	}

	// The login gate's env moved and nothing else did.
	env := rig.crEnv(t, naming.SystemLoginServer)
	if env[envRootDomain] != newNames.root || env[envPanelHostname] != newNames.panel || env[envAPIBaseURL] != platform.InternalAPIBaseURL("felis") {
		t.Fatalf("login env %v", env)
	}

	// The proxy's file: the three keys moved, its token and mode did not.
	props := rig.read(t, "felis-link.properties")
	if want := strings.NewReplacer("old.example", "new.example").Replace(linkPropsBody); props != want {
		t.Fatalf("felis-link.properties:\n%s", props)
	}
	if st, _ := os.Stat(rig.path("felis-link.properties")); st.Mode().Perm() != 0o640 {
		t.Fatalf("felis-link.properties mode %v", st.Mode().Perm())
	}

	if strings.Join(rig.events, ",") != "roll-api,restart felis-velocity" {
		t.Fatalf("events %v", rig.events)
	}
	if !strings.Contains(rig.out.String(), "Every surface is on new.example.") {
		t.Fatalf("the closing check did not pass:\n%s", rig.out)
	}
}

