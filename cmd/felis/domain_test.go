// domainRig models the host: the files, the cluster, and a felis-api, proxy and
// operator that pick up config the way the real ones do — the api serves what it
// read at its last restart, the proxy runs since its last restart, and the login
// pod carries the env its MinecraftServer had when it was last rolled.
type domainRig struct {
	h      domainHost
	cl     client.Client
	out    *bytes.Buffer
	dir    string
	events []string

	served      domainNames
	servedCert  *x509.Certificate
	proxySince  time.Time
	proxyLoaded bool
	unresolved  map[string]bool
	// The fake operator: the CR env the login pod was last rolled to, and how
	// many looks at the pod since the CR moved on.
	rolledTo string
	pending  int
}

func (rig *domainRig) path(name string) string { return filepath.Join(rig.dir, name) }

func newDomainRig(t *testing.T) *domainRig {
	t.Helper()
	rig := &domainRig{out: &bytes.Buffer{}, dir: t.TempDir(), proxyLoaded: true, unresolved: map[string]bool{}}
	writeTestFile(t, rig.path("felis.host.toml"), installerTOML("old.example", "127.0.0.1"), 0o600)
	writeTestFile(t, rig.path("felis.pod.toml"), installerTOML("old.example", "10.211.55.6"), 0o600)
	if err := os.Symlink(rig.path("felis.host.toml"), rig.path("felis.toml")); err != nil {
		t.Fatal(err)
	}
	certPEM, keyPEM, err := issuePanelCert(oldNames, []net.IP{net.ParseIP("10.211.55.6")}, time.Now())
	if err != nil {
		t.Fatal(err)
	}
	writeTestFile(t, rig.path("panel-tls.crt"), string(certPEM), 0o644)
	writeTestFile(t, rig.path("panel-tls.key"), string(keyPEM), 0o600)
	writeTestFile(t, rig.path("felis-link.properties"), linkPropsBody, 0o640)
	// The proxy started before its config was last written, which is how it
	// stands after an install.
	rig.proxySince = time.Now().Add(-time.Hour)

	pod := []byte(installerTOML("old.example", "10.211.55.6"))
	login, err := loginSystemServer("felis/limbo:1", "minecraft", platform.InternalAPIBaseURL("felis"), oldNames.root, oldNames.panel)
	if err != nil {
		t.Fatal(err)
	}
	lobby, err := lobbySystemServer("felis/lobby:1", "minecraft")
	if err != nil {
		t.Fatal(err)
	}
	loginPod := &corev1.Pod{
		ObjectMeta: metav1.ObjectMeta{Namespace: "minecraft", Name: naming.SystemLoginServer + "-0"},
		Spec:       corev1.PodSpec{Containers: []corev1.Container{{Name: "minecraft", Env: podEnv(login.Spec.Env)}}},
		Status:     corev1.PodStatus{Conditions: []corev1.PodCondition{{Type: corev1.PodReady, Status: corev1.ConditionTrue}}},
	}
	rig.rolledTo = envKey(login.Spec.Env)
	rig.cl = fake.NewClientBuilder().WithScheme(haltScheme(t)).WithInterceptorFuncs(interceptor.Funcs{
		Get: func(ctx context.Context, c client.WithWatch, key client.ObjectKey, obj client.Object, opts ...client.GetOption) error {
			if key.Name == naming.SystemLoginServer+"-0" {
				rig.operatorTick(t, c)
			}
			return c.Get(ctx, key, obj, opts...)
		},
	}).WithObjects(
		&corev1.Secret{ObjectMeta: metav1.ObjectMeta{Namespace: "felis", Name: platform.ConfigSecretName},
			Data: map[string][]byte{platform.ConfigSecretKey: pod}},
		&corev1.Secret{ObjectMeta: metav1.ObjectMeta{Namespace: "minecraft", Name: platform.ConfigSecretName},
			Data: map[string][]byte{platform.ConfigSecretKey: pod}},
		&corev1.Secret{ObjectMeta: metav1.ObjectMeta{Namespace: "felis", Name: platform.APITLSSecretName},
			Type: corev1.SecretTypeTLS, Data: map[string][]byte{corev1.TLSCertKey: certPEM, corev1.TLSPrivateKeyKey: keyPEM}},
		login, lobby, loginPod,
	).Build()
	rig.served = oldNames
	rig.servedCert, _ = x509.ParseCertificate(mustCertDER(certPEM))

	rig.h = domainHost{
		paths: domainPaths{
			hostTOML: rig.path("felis.host.toml"), podTOML: rig.path("felis.pod.toml"), defaultTOML: rig.path("felis.toml"),
			cert: rig.path("panel-tls.crt"), key: rig.path("panel-tls.key"),
			linkProps: rig.path("felis-link.properties"), tunnelConfig: rig.path("cloudflared.yml"),
		},
		cl:        rig.cl,
		controlNS: "felis",
		rollAPI: func(ctx context.Context) error {
			rig.events = append(rig.events, "roll-api")
			rig.restartAPI(t)
			return nil
		},
		restartUnit: func(_ context.Context, unit string) error {
			rig.events = append(rig.events, "restart "+unit)
			rig.proxySince = time.Now().Add(time.Second)
			return nil
		},
		unitState: func(context.Context, string) (unitStatus, error) {
			return unitStatus{loaded: rig.proxyLoaded, active: rig.proxyLoaded, since: rig.proxySince}, nil
		},
		liveAPI: func(context.Context, string) (liveAPIView, error) {
			return liveAPIView{names: rig.served, cert: rig.servedCert}, nil
		},
		lookupHost: func(_ context.Context, host string) ([]string, error) {
			if rig.unresolved[host] {
				return nil, errors.New("no such host")
			}
			return []string{"10.211.55.6"}, nil
		},
		passkeys:  func(context.Context) (int, int, error) { return 3, 2, nil },
		now:       time.Now,
		out:       rig.out,
		loginWait: 50 * time.Millisecond,
		pollEvery: time.Millisecond,
	}
	return rig
}

func podEnv(env []v1alpha1.EnvVar) []corev1.EnvVar {
	out := make([]corev1.EnvVar, len(env))
	for i, e := range env {
		out[i] = corev1.EnvVar{Name: e.Name, Value: e.Value}
	}
	return out
}

// restartAPI makes the fake felis-api load the config and certificate its
// Secrets hold now.
func (rig *domainRig) restartAPI(t *testing.T) {
	t.Helper()
	var cfg, tlsSec corev1.Secret
	ctx := context.Background()
	if err := rig.cl.Get(ctx, client.ObjectKey{Namespace: "felis", Name: platform.ConfigSecretName}, &cfg); err != nil {
		t.Fatal(err)
	}
	if err := rig.cl.Get(ctx, client.ObjectKey{Namespace: "felis", Name: platform.APITLSSecretName}, &tlsSec); err != nil {
		t.Fatal(err)
	}
	names, err := tomlDomainNames(cfg.Data[platform.ConfigSecretKey])
	if err != nil {
		t.Fatal(err)
	}
	rig.served = names
	rig.servedCert, err = x509.ParseCertificate(mustCertDER(tlsSec.Data[corev1.TLSCertKey]))
	if err != nil {
		t.Fatal(err)
	}
}

// rollLoginPod is the operator restarting the login pod onto its CR's env.
// operatorTick is the operator as the login pod is watched: once the CR's env
// changes it takes operatorLag looks at the pod before the restarted pod
// carries the new env, the way a real rollout lags the CR.
func (rig *domainRig) operatorTick(t *testing.T, c client.Client) {
	t.Helper()
	ctx := context.Background()
	var ms v1alpha1.MinecraftServer
	if err := c.Get(ctx, client.ObjectKey{Namespace: "minecraft", Name: naming.SystemLoginServer}, &ms); err != nil {
		t.Fatal(err)
	}
	if envKey(ms.Spec.Env) == rig.rolledTo {
		return
	}
	if rig.pending++; rig.pending < operatorLag {
		return
	}
	var pod corev1.Pod
	if err := c.Get(ctx, client.ObjectKey{Namespace: "minecraft", Name: naming.SystemLoginServer + "-0"}, &pod); err != nil {
		t.Fatal(err)
	}
	pod.Spec.Containers[0].Env = podEnv(ms.Spec.Env)
	if err := c.Update(ctx, &pod); err != nil {
		t.Fatal(err)
	}
	rig.rolledTo, rig.pending = envKey(ms.Spec.Env), 0
}

const operatorLag = 3

func envKey(env []v1alpha1.EnvVar) string {
	var b strings.Builder
	for _, e := range env {
		b.WriteString(e.Name + "=" + e.Value + "\n")
	}
	return b.String()
}

func (rig *domainRig) read(t *testing.T, name string) string {
	t.Helper()
	b, err := os.ReadFile(rig.path(name))
	if err != nil {
		t.Fatal(err)
	}
	return string(b)
}

func (rig *domainRig) secret(t *testing.T, ns, name string) map[string][]byte {
	t.Helper()
	var s corev1.Secret
	if err := rig.cl.Get(context.Background(), client.ObjectKey{Namespace: ns, Name: name}, &s); err != nil {
		t.Fatal(err)
	}
	return s.Data
}

func (rig *domainRig) crEnv(t *testing.T, name string) map[string]string {
	t.Helper()
	var ms v1alpha1.MinecraftServer
	if err := rig.cl.Get(context.Background(), client.ObjectKey{Namespace: "minecraft", Name: name}, &ms); err != nil {
		t.Fatal(err)
	}
	env := map[string]string{}
	for _, e := range ms.Spec.Env {
		env[e.Name] = e.Value
	}
	return env
}

// snapshot is every byte `set` may touch, for proving a refused or dry run
// touched none of it.
func (rig *domainRig) snapshot(t *testing.T) string {
	t.Helper()
	var b strings.Builder
	entries, _ := os.ReadDir(rig.dir)
	for _, e := range entries {
		b.WriteString(e.Name() + "\n" + rig.read(t, e.Name()) + "\n")
	}
	var lines []string
	for _, s := range []struct{ ns, name string }{{"felis", platform.ConfigSecretName}, {"minecraft", platform.ConfigSecretName}, {"felis", platform.APITLSSecretName}} {
		for k, v := range rig.secret(t, s.ns, s.name) {
			lines = append(lines, s.ns+"/"+s.name+"/"+k+"\n"+string(v))
		}
	}
	for k, v := range rig.crEnv(t, naming.SystemLoginServer) {
		lines = append(lines, "env "+k+"="+v)
	}
	sort.Strings(lines)
	b.WriteString(strings.Join(lines, "\n"))
	return b.String()
}

func TestNormalizeRootDomain(t *testing.T) {
	for in, want := range map[string]string{
		"Example.COM.":          "example.com",
		"  mc.example.org ":     "mc.example.org",
		"10.211.55.6.nip.io":    "10.211.55.6.nip.io",
		"xn--bcher-kva.example": "xn--bcher-kva.example",
	} {
		got, err := normalizeRootDomain(in)
		if err != nil || got != want {
			t.Errorf("normalizeRootDomain(%q) = %q, %v; want %q", in, got, err, want)
		}
	}
	for _, in := range []string{"", "https://example.com", "example.com:443", "example.com/x", "10.0.0.1", "::1",
		"localhost", "a_b.example", "-a.example", "a-.example", strings.Repeat("a", 64) + ".example",
		strings.Repeat("abcdefghi.", 25) + "example"} {
		if got, err := normalizeRootDomain(in); err == nil {
			t.Errorf("normalizeRootDomain(%q) = %q, want an error", in, got)
		}
	}
}

